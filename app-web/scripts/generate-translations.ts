// ── Deep merge utility ─────────────────────────────────
function deepMerge(base: Record<string, unknown>, overrides: Record<string, unknown>): Record<string, unknown> {
  const result = { ...base };

  for (const key of Object.keys(overrides)) {
    const baseVal = base[key];
    const overrideVal = overrides[key];

    if (
      baseVal && typeof baseVal === 'object' && !Array.isArray(baseVal) &&
      overrideVal && typeof overrideVal === 'object' && !Array.isArray(overrideVal)
    ) {
      result[key] = deepMerge(
        baseVal as Record<string, unknown>,
        overrideVal as Record<string, unknown>,
      );
    } else {
      result[key] = overrideVal;
    }
  }

  return result;
}

// ── Main ───────────────────────────────────────────────
function main() {
  // Read English base
  const enRaw = fs.readFileSync(EN_PATH, 'utf-8');
  const enBase = JSON.parse(enRaw) as Record<string, unknown>;

  let generated = 0;
  let skipped = 0;

  for (const locale of TARGET_LOCALES) {
    const targetPath = path.join(MESSAGES_DIR, `${locale}.json`);

    // Never overwrite existing files (e.g. pl.json)
    if (fs.existsSync(targetPath)) {
      console.log(`  SKIP  ${locale}.json (already exists)`);
      skipped++;
      continue;
    }

    const overrides = (TRANSLATIONS[locale] ?? {}) as Record<string, unknown>;
    const merged = deepMerge(enBase, overrides);

    fs.writeFileSync(targetPath, JSON.stringify(merged, null, 2) + '\n', 'utf-8');
    console.log(`  WRITE ${locale}.json`);
    generated++;
  }

  console.log(`\nDone: ${generated} generated, ${skipped} skipped.`);
}

main();
